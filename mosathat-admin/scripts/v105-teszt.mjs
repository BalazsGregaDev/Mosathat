  await c.waitForTimeout(700)
  const [kilog, alja, gorget] = await cs.evaluate((e) => [getComputedStyle(e).overflowY, Math.round(e.getBoundingClientRect().bottom), e.scrollHeight > e.clientHeight + 1])
